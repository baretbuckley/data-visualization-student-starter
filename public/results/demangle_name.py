import argparse
import csv
import re
from pathlib import Path


# Each rule describes:
#   1. A regex matching a postfix at the END of the name.
#   2. The columns to extract from that postfix.
#
# Named regex groups correspond to output column names.
#
# Rules are checked repeatedly until no more postfixes match.
# This allows multiple postfixes to be extracted from one name.

POSTFIX_RULES = [
    {
        "name": "matrix_dimensions",
        "pattern": r"/(?P<rows>\d+)/(?P<cols>\d+)$",
        "patern_names": ["row", "cols"],
        "columns": ["rows", "cols"],
        "mapping": None # (value, pattern_name)
    },
    # {
    #     "name": "size_operation",
    #     "pattern": r"/(?P<size>\d+)/(?P<operation>[A-Za-z_][A-Za-z0-9_]*)$",
    #     "columns": ["size", "operation"],
    # },
    {
        "name": "template",
        "pattern": (
            r"<(?P<type>[^,<>]+),\s*"
            r"(?P<dynamic>[^,<>]+),\s*"
            r"(?P<operation>[^<>]+)>$"
        ),
        "columns": ["type", "dynamic", "operation"],
        "mapping": None
    },
]


def demangle_name(name):

    if not name:
        return name, {}

    base_name = name.strip()
    extracted = {}

    # Continue extracting postfixes until no rule matches.
    while True:
        matched = False

        for rule in POSTFIX_RULES:
            match = re.search(rule["pattern"], base_name)

            if not match:
                continue

            pattern_values = match.groupdict()

            if rule["map"] != None:
                pass

