def map_column_names(columns: list[str]) -> list[str]:
    # Rename columns as needed.
    renamed_columns = []
    for col in columns:
        if col == "bool_op":
            continue
        else:
            renamed_columns.append(col)
    renamed_columns.append("type")
    return renamed_columns

def demangle_name(name: str) -> tuple[str, Dict[str, Any] | None]:

    if not name:
        return name, {}

    base_name = name.strip()
    extracted = {}

    invalid_name = False

    # Continue extracting postfixes until no rule matches.
    while True:
        matched = False

        for rule in POSTFIX_RULES:
            match = re.search(rule["pattern"], base_name)

            if not match:
                continue

            pattern_values_map = match.groupdict()
            # Convert to list ordered by rule["pattern_names"]
            values = [pattern_values_map.get(name) for name in rule["pattern_names"]]

            if "mapping" in rule and rule["mapping"] is not None:
                # Apply the mapping function to the extracted values.
                values = rule["mapping"](values)

            if values is None:
                invalid_name = True
                base_name = base_name[:match.start()].rstrip()
                matched = True
                break

            if len(values) != len(rule["columns"]):
                raise ValueError(
                    f"Rule '{rule['name']}' extracted {len(values)} values, "
                    f"but expected {len(rule['columns'])} columns."
                )



            for i, column in enumerate(rule["columns"]):

                value = values[i].strip()

                if column not in extracted:
                    extracted[column] = value
                else:
                    # Preserve repeated postfix values.
                    extracted[column] += ";" + value

            # Remove the matched postfix.
            base_name = base_name[:match.start()].rstrip()
            matched = True
            break

        if not matched:
            break

    if invalid_name:
        return base_name, None

    return base_name, extracted


def process_csv(input_path, output_path):
    with open(input_path, "r", newline="", encoding="utf-8-sig") as infile:
        reader = csv.DictReader(infile)

        if reader.fieldnames is None:
            raise ValueError("The input CSV is empty or has no header.")

        if "name" not in reader.fieldnames:
            raise ValueError('The CSV must contain a "name" column.')

        original_columns = list(reader.fieldnames)

        # All columns that can be generated by the configured rules.
        new_columns = [
            column
            for rule in POSTFIX_RULES
            for column in rule["columns"]
        ]

        # Preserve original column order and avoid duplicates.
        output_columns = original_columns.copy()

        for column in new_columns:
            if column not in output_columns:
                output_columns.append(column)

        output_columns = map_column_names(output_columns)

        with open(output_path, "w", newline="", encoding="utf-8") as outfile:
            writer = csv.DictWriter(
                outfile,
                fieldnames=output_columns,
                extrasaction="ignore",
            )

            writer.writeheader()

            for row in reader:
                original_name = row.get("name", "")

                base_name, extracted = demangle_name(original_name)

                if extracted is None:
                    continue


                # Replace the original name with its demangled version.
                row["name"] = base_name

                # Populate extracted columns.
                for column, value in extracted.items():
                    row[column] = value

                writer.writerow(map_row(row))

    print(f"Processed CSV saved to: {output_path}")


def main():
    # Ensure the output directory exists
    output_path = (Path(dest_major_path) / sub_dir / minor_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    input_path = Path(src_major_path) / sub_dir / minor_path
    output_path = Path(dest_major_path) / sub_dir / minor_path

    process_csv(input_path, output_path)


if __name__ == "__main__":
    main()