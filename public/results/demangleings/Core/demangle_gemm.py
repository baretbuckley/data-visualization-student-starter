# Each rule describes:
#   1. A regex matching a postfix at the END of the name.
#   2. The columns to extract from that postfix.
#
# Named regex groups correspond to output column names.
#
# Rules are checked repeatedly until no more postfixes match.
# This allows multiple postfixes to be extracted from one name.

src_major_path = "combined"
dest_major_path = "demangled"

sub_dir = "run2"
minor_path = "Core/bench_gemm.csv"



#Default rules
ROW_COL_RULE = {
    "name": "matrix_dimensions",
    "pattern": r"/(?P<rows>\d+)/(?P<cols>\d+)$",
    "pattern_names": ["row", "cols"],
    "columns": ["rows", "cols"],
    "mapping": None # (pattern_names) => (columns)
}

VEC_SIZE_RULE = {
    "name": "vector_size",
    "pattern": r"/(?P<size>\d+)$",
    "pattern_names": ["size"],
    "columns": ["size"],
}


# Set Rules here
POSTFIX_RULES = [
    {
        "name": "GEMM_matrix size",
        "pattern": r"/(?P<size1>\d+)/(?P<size2>\d+)/(?P<size3>\d+)$",
        "pattern_names": ["size1", "size2", "size3"],
        "columns": ["size"],
        "mapping": lambda cols: [cols[0]] if cols[0] == cols[1] and cols[1] == cols[2] else None  # (pattern_names) => (columns)|None
    },
]


